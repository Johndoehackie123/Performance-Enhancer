/**
 * Theme registration.
 *
 * Registers the visual styles as pickable color themes in Settings → Revenge →
 * Themes, so the palette survives restarts and — more importantly — reaches
 * every raw/semantic color Discord resolves for its UI, which is the only way
 * to re-skin surfaces the JSX layer never sees.
 *
 * Design notes:
 *   - Colors are computed lazily inside `getColors` (the Themes API calls it
 *     for the picker previews and on pick), so editing the palette in the
 *     plugin propagates to the Themes screen without re-registering.
 *   - Every structural surface (base tiers, modifier tints, text tiers) is
 *     derived from the same tonal scale the JSX recolorer uses, which keeps
 *     the two layers visually identical.
 *   - The light base is generated by lifting the panel toward white, so a
 *     light Discord base stays coherent with a custom dark panel instead of
 *     falling back to Discord's stock whites.
 *
 * Registering is best-effort: the API is optional, and a missing or older
 * themes plugin must never stop the rest of the plugin from starting. Note
 * the API has no unregister; palettes registered here stay in the picker
 * until Discord restarts.
 */
import { buildTokens, isDarkColor, shade, withAlpha } from './engine'
import type { ThemesApi, ThemeBase } from '@revenge-mod/themes-api/types'
import type { DeviceTier, StyleId, VisualSettings } from '../shared'

const GROUP = 'performance-enhancer'

interface ThemeSpec {
	id: StyleId
	name: string
	description: string
	/** Raw palette overrides. */
	raw: Record<string, string>
	/** Per-base semantic overrides. */
	semantic: Record<string, Record<string, string>>
}

/** The structural tiers shared by every theme, derived from one tonal scale. */
function semanticFor(scale: {
	base: string
	lowest: string
	lowestDeep: string
	elevated: string
	hover: string
	text: string
	muted: string
	accent: string
	accentSoft: string
	accentTint: string
	accentTintStrong: string
}): Record<ThemeBase, Record<string, string>> {
	const dark: Record<string, string> = {
		BACKGROUND_BASE_LOWEST: scale.lowestDeep,
		BACKGROUND_BASE_LOWER: scale.lowest,
		BACKGROUND_BASE_LOW: scale.base,
		BACKGROUND_BASE_HIGH: scale.elevated,
		BACKGROUND_BASE_HIGHEST: scale.elevated,
		BACKGROUND_MODIFIER_HOVER: scale.hover,
		BACKGROUND_MODIFIER_ACTIVE: scale.elevated,
		BACKGROUND_MODIFIER_SELECTED: scale.accentTint,
		BACKGROUND_MODIFIER_ACCENT: scale.accentTint,
		BACKGROUND_MODIFIER_STAGING: scale.hover,
		BACKGROUND_FLOATING: scale.elevated,
		TEXT_LINK: scale.accent,
		TEXT_BRAND: scale.accent,
		TEXT_NORMAL: scale.text,
		TEXT_DEFAULT: scale.text,
		TEXT_MUTED: scale.muted,
		HEADER_PRIMARY: scale.text,
		HEADER_SECONDARY: scale.muted,
		INTERACTIVE_NORMAL: scale.muted,
		INTERACTIVE_HOVER: scale.text,
		INTERACTIVE_ACTIVE: scale.accent,
		INTERACTIVE_MUTED: scale.muted,
		CHANNELS_DEFAULT: scale.muted,
		CHANNELS_ICON: scale.muted,
		CHANNELS_SELECTED: scale.text,
		BRAND_500: scale.accent,
		BRAND_560: scale.accentSoft,
	}

	const deeper = (hex: string, by: number) => shade(hex, -by)

	const darker = {
		...dark,
		BACKGROUND_BASE_LOWEST: deeper(scale.lowestDeep, 12),
		BACKGROUND_BASE_LOWER: deeper(scale.lowest, 12),
		BACKGROUND_BASE_LOW: deeper(scale.base, 10),
		BACKGROUND_BASE_HIGH: deeper(scale.elevated, 10),
		BACKGROUND_BASE_HIGHEST: deeper(scale.elevated, 10),
		BACKGROUND_MODIFIER_HOVER: deeper(scale.hover, 8),
		BACKGROUND_MODIFIER_ACTIVE: deeper(scale.elevated, 8),
		BACKGROUND_FLOATING: deeper(scale.elevated, 10),
	}

	const midnight = {
		...dark,
		BACKGROUND_BASE_LOWEST: deeper(scale.lowestDeep, 30),
		BACKGROUND_BASE_LOWER: deeper(scale.lowest, 28),
		BACKGROUND_BASE_LOW: deeper(scale.base, 24),
		BACKGROUND_BASE_HIGH: deeper(scale.elevated, 22),
		BACKGROUND_BASE_HIGHEST: deeper(scale.elevated, 22),
		BACKGROUND_MODIFIER_HOVER: deeper(scale.hover, 22),
		BACKGROUND_MODIFIER_ACTIVE: deeper(scale.elevated, 16),
		BACKGROUND_FLOATING: deeper(scale.elevated, 20),
	}

	// Lift the panel toward white so the light base stays tinted to the
	// custom palette rather than reverting to Discord's stock greys.
	const lift = (hex: string) => (isDarkColor(hex) ? shade(hex, 88) : hex)
	const lightBase = lift(scale.base)
	const lightText = '#1c1e24'
	const lightTextMuted = withAlpha(lightText, 0.64)

	const light = {
		BACKGROUND_BASE_LOWEST: lift(deeper(scale.base, 12)),
		BACKGROUND_BASE_LOWER: lift(deeper(scale.base, 6)),
		BACKGROUND_BASE_LOW: lightBase,
		BACKGROUND_BASE_HIGH: isDarkColor(scale.base) ? shade(lightBase, -8) : shade(lightBase, 4),
		BACKGROUND_BASE_HIGHEST: isDarkColor(scale.base) ? shade(lightBase, -8) : shade(lightBase, 4),
		BACKGROUND_MODIFIER_HOVER: withAlpha('#000000', 0.06),
		BACKGROUND_MODIFIER_ACTIVE: withAlpha('#000000', 0.1),
		BACKGROUND_MODIFIER_SELECTED: scale.accentTint,
		BACKGROUND_MODIFIER_ACCENT: scale.accentTint,
		BACKGROUND_MODIFIER_STAGING: withAlpha('#000000', 0.06),
		BACKGROUND_FLOATING: '#ffffff',
		TEXT_LINK: scale.accent,
		TEXT_BRAND: scale.accent,
		TEXT_NORMAL: lightText,
		TEXT_DEFAULT: lightText,
		TEXT_MUTED: lightTextMuted,
		HEADER_PRIMARY: lightText,
		HEADER_SECONDARY: lightTextMuted,
		INTERACTIVE_NORMAL: lightTextMuted,
		INTERACTIVE_HOVER: lightText,
		INTERACTIVE_ACTIVE: scale.accent,
		INTERACTIVE_MUTED: lightTextMuted,
		CHANNELS_DEFAULT: lightTextMuted,
		CHANNELS_ICON: lightTextMuted,
		CHANNELS_SELECTED: lightText,
		BRAND_500: scale.accent,
		BRAND_560: scale.accentSoft,
	}

	return { dark, darker, midnight, light }
}

/** Raw brand scale derived from one accent, so every accent-colored control follows. */
function rawBrand(accent: string, accentSoft: string): Record<string, string> {
	// `shade` passes non-hex input through unchanged, so an rgba accent degrades
	// to a flat scale instead of throwing.
	return {
		BRAND_230: shade(accent, 26),
		BRAND_300: shade(accent, 18),
		BRAND_400: shade(accent, 10),
		BRAND_500: accent,
		BRAND_560: accentSoft,
		BRAND_600: shade(accent, -22),
		BRAND_700: shade(accent, -34),
	}
}

function specs(
	tokenFor: (style: StyleId) => ReturnType<typeof buildTokens>,
): ThemeSpec[] {
	const tokensFor = tokenFor

	const material = tokensFor('material')
	const glass = tokensFor('glass')
	const frost = tokensFor('frost')
	const card = tokensFor('card')
	const custom = tokensFor('custom')

	return [
		{
			id: 'material',
			name: 'Material 3',
			description: 'Tonal elevated surfaces with an indigo accent.',
			raw: rawBrand(material.accent, material.accentSoft),
			semantic: semanticFor(material),
		},
		{
			id: 'glass',
			name: 'Glassmorphism',
			description: 'Translucent panes; pair it with a background image.',
			raw: rawBrand(glass.accent, glass.accentSoft),
			semantic: semanticFor(glass),
		},
		{
			id: 'frost',
			name: 'Liquid Frost',
			description: 'Cool, milky surfaces for a frosted-glass look.',
			raw: rawBrand(frost.accent, frost.accentSoft),
			semantic: semanticFor(frost),
		},
		{
			id: 'card',
			name: 'Soft Cards',
			description: 'Low-contrast rounded surfaces with a gentle shadow.',
			raw: rawBrand(card.accent, card.accentSoft),
			semantic: semanticFor(card),
		},
		{
			id: 'custom',
			name: 'Custom palette',
			description: 'Your own accent and panel colours from the Style studio.',
			raw: rawBrand(custom.accent, custom.accentSoft),
			semantic: semanticFor(custom),
		},
	]
}

/**
 * Registers the plugin's color themes.
 *
 * @param themes The optional Themes API, or `undefined` when absent.
 * @param getVisual Live accessor for the user's current visual settings, so
 *   `getColors` picks up palette edits without re-registering.
 * @returns a cleanup function, or `undefined` when the Themes API is absent so
 * callers can tell "registered" from "nothing to clean up".
 */
export function registerThemes(
	themes: ThemesApi | undefined,
	getVisual: () => VisualSettings,
	tier: DeviceTier,
): (() => void) | undefined {
	if (!themes || typeof themes.registerTheme !== 'function') return undefined

	try {
		themes.registerGroup(GROUP, {
			name: 'Performance Enhancer',
			description: 'Material, glassmorphism, liquid frost, soft cards and your custom palette.',
		})
	} catch {
		// A duplicate group must not abort the theme registrations.
	}

	// Memoize per palette so the Themes screen's preview path stays cheap.
	// `{ ...visual, style }` creates a fresh object, which buildTokens' own memo
	// would otherwise miss.
	const paletteCache = new Map<StyleId, { source: VisualSettings; tokens: ReturnType<typeof buildTokens> }>()
	const tokenFor = (style: StyleId) => {
		const current = getVisual()
		const hit = paletteCache.get(style)
		if (hit && hit.source === current) return hit.tokens
		const tokens = buildTokens({ ...current, style }, tier)
		paletteCache.set(style, { source: current, tokens })
		return tokens
	}

	let specList: ThemeSpec[] = []
	try {
		specList = specs(tokenFor)
	} catch (error) {
		// A settings corruption must not break the plugin; skip theme registration.
		console.warn(`[performance-enhancer] could not build theme specs: ${String(error)}`)
		return undefined
	}

	for (const spec of specList) {
		try {
			themes.registerTheme(GROUP, `pe-${spec.id}`, {
				name: spec.name,
				description: spec.description,
				getColors: () => {
					// Rebuild lazily so previews and picks always see the current palette.
					try {
						const tokens = tokenFor(spec.id)
						return {
							raw: rawBrand(tokens.accent, tokens.accentSoft),
							semantic: semanticFor(tokens) as never,
						}
					} catch {
						return {
							raw: spec.raw,
							semantic: spec.semantic as never,
						}
					}
				},
			})
		} catch {
			// A theme shape mismatch must not stop the remaining themes.
		}
	}

	return () => {
		// The Themes API has no unregister; palettes stay in the picker until
		// Discord restarts. Documented in the settings screen.
	}
}
